import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fetchArkadec } from "./get-arkadec.mjs";

const CONTRACTS = [
    { stem: "dust_covenant", module: "dust-covenant-artifact.ts", constant: "V2_ARTIFACT" },
    {
        stem: "carrier_account",
        module: "carrier-account-artifact.ts",
        constant: "CARRIER_ARTIFACT",
    },
];

const bin = await fetchArkadec();
const scratch = mkdtempSync(join(tmpdir(), "arkadec-"));
try {
    for (const { stem, module, constant } of CONTRACTS) {
        const src = resolve(`packages/covenant/contracts/${stem}.ark`);
        const out = resolve(`packages/covenant/contracts/${stem}.json`);
        const mod = resolve(`packages/covenant/src/${module}`);
        const raw = join(scratch, `${stem}.json`);
        execFileSync(bin, [src, "-o", raw], { stdio: "inherit" });
        const artifact = JSON.parse(readFileSync(raw, "utf8"));
        // A wall-clock stamp would make the committed-diff gate fail on every run.
        delete artifact.updatedAt;
        writeFileSync(out, `${JSON.stringify(artifact, null, 2)}\n`);

        // Only the fields programFromArtifact reads, so the embedded source bundle
        // does not ride into the browser client. Left unannotated on purpose: arkadec
        // emits a witness `encoding` the vendored SDK's ArtifactWitnessElement lacks,
        // which a declared ContractArtifact would reject as an excess property.
        const { contractName, constructorInputs, functions } = artifact;
        writeFileSync(
            mod,
            [
                `// Generated by scripts/gen-artifact.mjs from contracts/${stem}.ark.`,
                "// Do not edit: `pnpm artifact` rewrites it and CI diffs the result.",
                `export const ${constant} = ${JSON.stringify(
                    { contractName, constructorInputs, functions },
                    null,
                    4,
                )};`,
                "",
            ].join("\n"),
        );
        console.log(`wrote ${out}\nwrote ${mod}`);
    }
} finally {
    rmSync(scratch, { recursive: true, force: true });
}
